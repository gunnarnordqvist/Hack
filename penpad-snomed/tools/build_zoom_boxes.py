"""Measure the close-up boxes (leg, back) of the body figure: writes web/zoomboxes.js.

  python tools/build_zoom_boxes.py        # needs Playwright (node), like tools/bbox_parts.cjs

The numbers are bounding boxes and label positions measured on web/vendor/bodypaths.js; they contain no drawing data of their own.
"""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEG = ["thigh", "knee", "lowerleg", "ankle", "foot"]
BACK = ["neck", "back", "shoulder", "hip", "buttock"]


def load_body():
    s = (ROOT / "web" / "vendor" / "bodypaths.js").read_text(encoding="utf8")
    return json.loads(s[s.index("export const BODY = ") + len("export const BODY = "):].rstrip().rstrip(";"))


def union(boxes, pad):
    x0 = min(b["x"] for b in boxes)
    y0 = min(b["y"] for b in boxes)
    x1 = max(b["x"] + b["w"] for b in boxes)
    y1 = max(b["y"] + b["h"] for b in boxes)
    return [round(x0 - pad), round(y0 - pad), round(x1 - x0 + 2 * pad), round(y1 - y0 + 2 * pad)]


def main():
    body = load_body()
    parts = {v: [{"slug": f"{s['region']}:{s['side'] or ''}", "paths": s["paths"]} for s in body[v]] for v in ("front", "back")}
    with tempfile.TemporaryDirectory() as d:
        pj, bj = Path(d) / "parts.json", Path(d) / "boxes.json"
        pj.write_text(json.dumps(parts), encoding="utf8")
        subprocess.run(["node", str(ROOT / "tools" / "bbox_parts.cjs"), str(pj), str(bj)], check=True)
        boxes = json.loads(bj.read_text(encoding="utf8"))
    out = {"leg": {}, "back": {}}
    for side in ("left", "right"):
        bs = [b for r in LEG for b in boxes["front"][f"{r}:{side}"]]
        out["leg"][side] = {"box": union(bs, 40), "anchors": {}}
        for r in LEG:
            bb = boxes["front"][f"{r}:{side}"]
            u = union(bb, 0)
            out["leg"][side]["anchors"][r] = [u[0] + u[2] // 2, u[1] + u[3] // 2]
    bs = [b for r in BACK for k, v in boxes["back"].items() if k.split(":")[0] == r for b in v]
    out["back"] = {"box": union(bs, 30), "anchors": {}}
    for r in BACK:
        for k, v in boxes["back"].items():
            if k.split(":")[0] == r:
                u = union(v, 0)
                out["back"]["anchors"][k] = [u[0] + u[2] // 2, u[1] + u[3] // 2]
    # the back view sits in the right half of the sheet: the box numbers are already in that coordinate system
    js = "// GENERATED by tools/build_zoom_boxes.py: measured boxes and label positions for the leg and back close-ups.\n"
    js += "export const ZOOM_BOXES = " + json.dumps(out) + ";\n"
    (ROOT / "web" / "zoomboxes.js").write_text(js, encoding="utf8")
    print("wrote web/zoomboxes.js", json.dumps({k: (v["box"] if "box" in v else {s: x["box"] for s, x in v.items()}) for k, v in out.items()}))


if __name__ == "__main__":
    sys.exit(main())
